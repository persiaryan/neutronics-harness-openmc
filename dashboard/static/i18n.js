const I18N = (() => {
  const storageKey = 'neutronics-dashboard-language';
  let language = 'en';
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === 'en' || saved === 'fr') language = saved;
  } catch { /* Storage can be disabled. English remains the default. */ }
  function t(source, params = {}) {
    const text = language === 'en' && Object.hasOwn(UI_ENGLISH, source) ? UI_ENGLISH[source] : source;
    return String(text).replace(/\{(\w+)\}/g, (match, key) =>
      Object.hasOwn(params, key) ? String(params[key]) : match);
  }
  function setLanguage(value) {
    language = value === 'fr' ? 'fr' : 'en';
    try { localStorage.setItem(storageKey, language); } catch { /* Session choice still works. */ }
  }
  return {t, setLanguage, get language() { return language; },
          get locale() { return language === 'fr' ? 'fr-FR' : 'en-US'; }};
})();
